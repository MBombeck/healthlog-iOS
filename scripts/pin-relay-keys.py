#!/usr/bin/env python3
"""Pin the push relay's identity keys into the build (#190 §1).

Usage: scripts/pin-relay-keys.py [keys.json] [--check]

keys.json is the relay release's `keys/<host>.json`:
    { "host": "push.healthlog.dev", "current": "<base64url 32>", "next": "<base64url 32>",
      "emergency": "<base64url 32>" }
Default: Config/push-relay/push.healthlog.dev.json. The script validates the file (host, unpadded
base64url, 32 bytes each, current and next both or neither present,
emergency optional and only beside them), copies it to Config/push-relay/<host>.json and
writes HealthLog/PushRelay/HLPushRelayPin.swift. --check only verifies that the Swift file matches
the JSON and exits 1 on drift. The app never fetches these keys at run time.
"""
import base64
import json
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT = os.path.join(ROOT, "Config", "push-relay", "push.healthlog.dev.json")
SWIFT = os.path.join(ROOT, "HealthLog", "PushRelay", "HLPushRelayPin.swift")
ALPHABET = set("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_")


def key_ok(text):
    if text == "":
        return True
    if not set(text) <= ALPHABET or len(text) != 43:
        return False
    return len(base64.urlsafe_b64decode(text + "=")) == 32


def render(spec):
    return (
        "// Generated by scripts/pin-relay-keys.py from Config/push-relay/%s.json.\n"
        "// Do not edit by hand: replace the JSON with the relay release's keys/<host>.json and run the script.\n"
        "// Empty keys mean \"not pinned yet\": every relay answer is then a transport error (#190 §1).\n"
        "\n"
        "enum HLPushRelayPin {\n"
        "    static let host = \"%s\"\n"
        "    static let current = \"%s\"\n"
        "    static let next = \"%s\"\n"
        "    /// Offline key, never deployed; the relay signs with it only if\n"
        "    /// current and next are both lost (#190).\n"
        "    static let emergency = \"%s\"\n"
        "}\n" % (spec["host"], spec["host"], spec["current"], spec["next"], spec["emergency"])
    )


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv[1:]
    path = args[0] if args else DEFAULT
    with open(path, encoding="utf-8") as f:
        spec = json.load(f)
    host = spec.get("host", "")
    if not host or "/" in host or ":" in host:
        print("pin-relay-keys: invalid host", file=sys.stderr)
        return 1
    current, nxt = spec.get("current", ""), spec.get("next", "")
    emergency = spec.get("emergency", "")
    if not (key_ok(current) and key_ok(nxt)) or (current == "") != (nxt == ""):
        print("pin-relay-keys: current and next must both be base64url 32-byte keys (or both empty)", file=sys.stderr)
        return 1
    if not key_ok(emergency) or (emergency and not current):
        print("pin-relay-keys: emergency must be a base64url 32-byte key beside current and next", file=sys.stderr)
        return 1
    if emergency and len({current, nxt, emergency}) != 3:
        print("pin-relay-keys: current, next and emergency must differ", file=sys.stderr)
        return 1
    spec = {"host": host, "current": current, "next": nxt, "emergency": emergency}
    rendered = render(spec)
    if check:
        with open(SWIFT, encoding="utf-8") as f:
            if f.read() != rendered:
                print("pin-relay-keys: HLPushRelayPin.swift does not match the keys file", file=sys.stderr)
                return 1
        print("pin-relay-keys: pinned keys match %s" % os.path.relpath(path, ROOT))
        return 0
    target = os.path.join(ROOT, "Config", "push-relay", "%s.json" % host)
    if os.path.abspath(path) != os.path.abspath(target):
        shutil.copyfile(path, target)
    with open(SWIFT, "w", encoding="utf-8") as f:
        f.write(rendered)
    print("pin-relay-keys: pinned %s (%s)" % (host, "keys present" if current else "no keys yet"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
